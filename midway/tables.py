"""LaTeX tables for the midway report (SPEC §7.1–7.2), written to report/tables/.

Every number comes from runs/aggregate.json (real, cross-checked runs only). Anything else renders as
\\tbd (a gray dash defined in main.tex). Paper numbers appear only in cells labeled as paper.

Which runs feed which cells (Tables 1, 2, 4 span both columns; Table 3 fits one):
  Table 1  one column per decoding setting (norsnorb, rs, full); cells are "paper / ours".
  Table 2  BrickGPT row: Stable@1 = % stable of the RS-only run; every other column from the RS+RB run.
  Table 3  DPO-local window sweep: no runs yet, all \\tbd.
  Table 4  BrickGPT reference row: Stable@1 from RS-only; other columns from RS+RB.

Run:  make report
"""
import math

from midway.aggregate import load_aggregate, primary_run_set
from midway.config import BOOTSTRAP_N, PAPER_TABLE1, SETTINGS, TABLES_DIR

TBD = r'\tbd'

# kind -> (scale, decimals of the value, decimals of the ± half-width)
FORMATS = {'pct': (100, 1, 1), 'stab': (1, 3, 2), 'sec': (1, 1, 1), 'count': (1, 1, 1), 'score': (1, 3, 2)}


def is_missing(x) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def fmt_ci(ci: dict | None, kind: str) -> str:
    """'mean\\textsubscript{±half-width}' for a metric dict {mean, lo, hi, n}; \\tbd if missing/undefined.

    The ± value is half the width of the 95% percentile bootstrap CI.
    """
    if ci is None or is_missing(ci.get('mean')) or is_missing(ci.get('lo')) or is_missing(ci.get('hi')):
        return TBD
    scale, decimals, hw_decimals = FORMATS[kind]
    half_width = scale * (ci['hi'] - ci['lo']) / 2
    return f'{scale * ci["mean"]:.{decimals}f}\\textsubscript{{\\,$\\pm${half_width:.{hw_decimals}f}}}'


def fmt_paper(value, kind: str) -> str:
    """Paper number with the same scale as ours (paper % values are already in percent). 'n/r' if not reported."""
    if value is None:
        return 'n/r'
    decimals = FORMATS[kind][1]
    return f'{value:.{decimals}f}'


def metric(run_set: dict | None, name: str) -> dict | None:
    return None if run_set is None else run_set['metrics'].get(name)


def header_comment(run_sets: list[dict | None]) -> str:
    runs = [run for rs in run_sets if rs for run in rs['runs']]
    return f'% generated by midway/tables.py from runs/aggregate.json ({", ".join(runs) or "no runs yet"})\n'


def provenance(run_set: dict | None) -> str:
    """'full250, n=250, s42' label for a column (actual n of prompts evaluated); \\tbd if there is no run.

    A run with fewer prompts than its prompt set shows 'n=180 of 250'; a run marked partial in run_meta.json
    (e.g. first100) shows 'n=100, partial'. CIs in that column are computed from those n prompts.
    """
    if run_set is None:
        return TBD
    n = f'n={run_set["n_prompts"]}'
    if run_set.get('expected_n') and run_set['n_prompts'] < run_set['expected_n']:
        n += f' of {run_set["expected_n"]}'
    elif run_set.get('partial'):
        n += ', partial'
    return f'{run_set["prompts"]}, {n}, s{"/".join(map(str, run_set["seeds"]))}'


def gpu_text(run_sets: list[dict | None]) -> str:
    gpus = sorted({rs['gpu'] for rs in run_sets if rs and rs['gpu']})
    return ', '.join(gpus) if gpus else TBD


def tabular(columns: str, header: list[str], rows: list[list[str]], extra_header: list[str] | None = None) -> str:
    lines = [f'\\begin{{tabular}}{{{columns}}}', r'\toprule', ' & '.join(header) + r' \\']
    if extra_header:
        lines.append(' & '.join(extra_header) + r' \\')
    lines.append(r'\midrule')
    lines += [' & '.join(row) + r' \\' for row in rows]
    lines += [r'\bottomrule', r'\end{tabular}']
    return '\n'.join(lines)


def float_env(env: str, label: str, caption: str, body: str, comment: str) -> str:
    return (f'{comment}\\begin{{{env}}}[t]\n\\centering\\footnotesize\n\\setlength{{\\tabcolsep}}{{4pt}}\n'
            f'\\caption{{{caption}}}\n\\label{{{label}}}\n{body}\n\\end{{{env}}}\n')


CI_NOTE = (f'$\\pm$ is half the width of a 95\\% percentile bootstrap CI ({BOOTSTRAP_N:,} resamples '
           f'over prompts).').replace(',', '{,}')


# ---------------------------------------------------------------- Table 1

TABLE1_ROWS = [  # (label, metric name, kind)
    (r'\% valid', 'valid', 'pct'),
    (r'\% stable', 'stable', 'pct'),
    ('Mean stab.', 'mean_stab', 'stab'),
    ('Min.\\ stab.', 'min_stab', 'stab'),
    ('CLIP', 'clip', 'score'),
    ('DINO', 'dino', 'score'),
    ('Rollbacks (median)', 'rollbacks_median', 'count'),
    ('Sec.\\ per build (median)', 'sec_per_build_median', 'sec'),
]
TABLE1_SETTINGS = ['norsnorb', 'rs', 'full']
RB_OFF = r'n/a (RB off)'  # rollbacks cell for settings with rollback off (max_regenerations 0)


def rollback_off(setting: str) -> bool:
    return SETTINGS[setting]['max_regenerations'] == 0


def table1(agg: dict) -> str:
    """Replication table: rows = metrics, columns = decoding settings, cells = 'paper / ours'."""
    run_sets = [primary_run_set(agg, s) for s in TABLE1_SETTINGS]
    rows = []
    for label, name, kind in TABLE1_ROWS:
        row = [label]
        for setting, rs in zip(TABLE1_SETTINGS, run_sets):
            if name == 'rollbacks_median' and rollback_off(setting):
                row.append(RB_OFF)
                continue
            paper = PAPER_TABLE1[setting].get(name)
            row.append(f'{fmt_paper(paper, kind)} / {fmt_ci(metric(rs, name), kind)}')
        rows.append(row)
    header = [''] + [SETTINGS[s]['label'] for s in TABLE1_SETTINGS]
    extra = [r'\scriptsize ours:'] + [r'\scriptsize ' + provenance(rs) for rs in run_sets]
    caption = (r'Replication of BrickGPT (Pun et al., Table~1). Cells are \emph{paper / ours}; ours is the mean over '
               r'the $n$ prompts and seeds shown under each column. ' + CI_NOTE +
               r' Rates are over all $n$ prompts; stability, CLIP and DINO are over valid builds only. '
               r'Stability: min.\ stab.\ $=1-$max stress, mean stab.\ $=1-$mean stress (raw). Upstream caps stress '
               r'at 1, so raw equals clipped and an unstable build has min.\ stab.\ 0. '
               f'GPU: {gpu_text(run_sets)}. '
               r'\tbd: not run yet; n/r: not reported in the paper.')
    # table* (both columns): three "paper / ours±CI" cells do not fit a 3.3 in column at 8 pt.
    return float_env('table*', 'tab:replication', caption, tabular('lccc', header, rows, extra),
                     header_comment(run_sets))


# ---------------------------------------------------------------- Tables 2-4 (skeletons)

def skeleton_rows(labels: list[str], n_cols: int) -> list[list[str]]:
    return [[label] + [TBD] * n_cols for label in labels]


def table2(agg: dict) -> str:
    """Main comparison (RQ2/RQ3). Only the BrickGPT row has real numbers."""
    rs, full = primary_run_set(agg, 'rs'), primary_run_set(agg, 'full')
    brickgpt = ['BrickGPT (ours)', fmt_ci(metric(rs, 'stable'), 'pct'), fmt_ci(metric(full, 'stable'), 'pct'),
                fmt_ci(metric(full, 'rollbacks_median'), 'count'), fmt_ci(metric(full, 'sec_per_build_median'), 'sec'),
                fmt_ci(metric(full, 'clip'), 'score'), fmt_ci(metric(full, 'dino'), 'score'),
                fmt_ci(metric(full, 'iou'), 'score'), fmt_ci(metric(full, 'n_bricks'), 'count')]
    rows = [brickgpt] + skeleton_rows(['RFT', 'DPO-seq', 'DPO-prefix (BrickDPO)', 'DPO-local (ours)'], 8)
    header = ['Model', 'Stable@1', r'Final \% stable', 'Rollbacks', 'Sec./build', 'CLIP', 'DINO', 'IoU', r'\#bricks']
    caption = (r'Main comparison (RQ2/RQ3). Stable@1: \% stable with rejection sampling and no rollback. '
               r'Final \% stable, rollbacks (median), sec./build (median): full decoding with rollback. '
               r'IoU: voxel IoU with the ground-truth build. BrickGPT Stable@1 is from the RS-only run '
               f'({provenance(rs)}); its other columns are from the RS+RB run ({provenance(full)}). '
               + CI_NOTE + r' \tbd: not run yet.')
    return float_env('table*', 'tab:main', caption, tabular('l' + 'c' * 8, header, rows), header_comment([rs, full]))


def table3(agg: dict) -> str:
    """Window sweep (RQ3) for DPO-local. No runs yet."""
    rows = skeleton_rows([f'DPO-local, $m={m}$' for m in (1, 5, 20)], 4)
    header = ['Model', 'Stable@1', 'Rollbacks', r'\#bricks', 'IoU']
    caption = r'Window-size sweep for DPO-local at a fixed pair budget (RQ3). \tbd: not run yet.'
    return float_env('table', 'tab:window', caption, tabular('lcccc', header, rows), header_comment([]))


def table4(agg: dict) -> str:
    """Shape-filter ablation (RQ4). Only the BrickGPT reference row has real numbers."""
    rs, full = primary_run_set(agg, 'rs'), primary_run_set(agg, 'full')
    brickgpt = ['BrickGPT (reference)', fmt_ci(metric(rs, 'stable'), 'pct'),
                fmt_ci(metric(full, 'clip'), 'score'), fmt_ci(metric(full, 'dino'), 'score'),
                fmt_ci(metric(full, 'iou'), 'score'), fmt_ci(metric(full, 'n_bricks'), 'count'),
                fmt_ci(metric(full, 'height'), 'count'), fmt_ci(metric(full, 'footprint'), 'count'),
                fmt_ci(metric(full, 'frac_1x1'), 'pct')]
    rows = skeleton_rows(['DPO-local, with IoU filter', 'DPO-local, no IoU filter'], 8) + [brickgpt]
    header = ['Model', 'Stable@1', 'CLIP', 'DINO', 'IoU', r'\#bricks', 'Height', 'Footprint', r'\% 1$\times$1']
    caption = (r'Shape-filter ablation (RQ4). Height: layers; footprint: occupied cells seen from above; '
               r'\% 1$\times$1: share of 1$\times$1 bricks; shape statistics are over all parsed builds. '
               f'BrickGPT Stable@1 from the RS-only run ({provenance(rs)}), other columns from the RS+RB run '
               f'({provenance(full)}). ' + CI_NOTE + r' \tbd: not run yet.')
    return float_env('table*', 'tab:shape', caption, tabular('l' + 'c' * 8, header, rows), header_comment([rs, full]))


def main() -> None:
    agg = load_aggregate()
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    for setting in TABLE1_SETTINGS:
        rs = primary_run_set(agg, setting)
        used = 'runs: ' + ', '.join(rs['runs']) if rs else 'no reportable run, cells are \\tbd'
        print(f'  Table column {setting}: {used}')
    for name, make in [('table1_replication', table1), ('table2_main', table2),
                       ('table3_window', table3), ('table4_shape', table4)]:
        path = TABLES_DIR / f'{name}.tex'
        path.write_text(make(agg))
        print(f'Wrote {path}')


if __name__ == '__main__':
    main()
